
import { useState } from 'react';
import { signUp } from '../services/auth/signUp.service';

type UseSignUpResult = {
  isLoading: boolean;
  error: string | null;
  isConfirmationPending: boolean;
  submitSignUp: (
    email: string,
    password: string,
    username?: string,
  ) => Promise<boolean>;
  clearError: () => void;
};

/**
 * Manages the signup flow, including loading, error, and email-confirmation state.
 *
 * Calls the signup service and exposes a simple interface for the registration UI.
 *
 * @returns Signup state, a submit handler, and an error-reset handler.
 */
export function useSignUp(): UseSignUpResult {
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [isConfirmationPending, setIsConfirmationPending] =
    useState(false);

  /**
   * Submits registration details to Supabase Auth.
   *
   * @param email - The user's email address.
   * @param password - The user's password.
   * @param username - Optional username; generated by the database if omitted.
   * @returns True when signup succeeds, otherwise false.
   */
  async function submitSignUp(
    email: string,
    password: string,
    username?: string,
  ): Promise<boolean> {
    setIsLoading(true);
    setError(null);
    setIsConfirmationPending(false);

    try {
      const data = await signUp({ email, password, username });

      if (data.user && !data.session) {
        setIsConfirmationPending(true);
      }

      return Boolean(data.user);
    } catch (err: unknown) {
      setError(
        err instanceof Error
          ? err.message
          : 'Unable to create your account. Please try again.',
      );

      return false;
    } finally {
      setIsLoading(false);
    }
  }

  /**
   * Clears the current signup error.
   */
  function clearError(): void {
    setError(null);
  }

  return {
    isLoading,
    error,
    isConfirmationPending,
    submitSignUp,
    clearError,
  };
}
